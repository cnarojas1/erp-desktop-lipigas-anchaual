import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.BASE_URL || 'http://127.0.0.1:8765/';
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext();
const page = await context.newPage();
const errors = [];
page.on('pageerror', e => errors.push(e.message));
page.on('console', m => { if (m.type() === 'error') console.log('console:', m.text()); });
page.setDefaultTimeout(5000);
try {
  await page.goto(new URL('app.html', base).href);
  await page.getByText('Abrir Aplicación', { exact: true }).click();
  await page.locator('#username').waitFor({ state: 'visible' });
  await page.getByRole('button', { name: 'Entrar', exact: true }).click();
  await page.locator('#dashboard').waitFor({ state: 'visible' });
  assert.equal(await page.locator('#userName').textContent(), 'Administrador');
  assert.deepEqual(errors, []);
  console.log('PASS fresh demo login');
  await page.reload();
  await page.getByText('Abrir Aplicación', { exact: true }).click();
  await page.locator('#password').fill('incorrect-password');
  await page.getByRole('button', { name: 'Entrar', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: 'Usuario o contraseña incorrectos' }).waitFor();
  assert.equal(await page.locator('#dashboard').isVisible(), false);
  await page.locator('#password').fill('admin123');
  await page.getByRole('button', { name: 'Entrar', exact: true }).click();
  await page.locator('#dashboard').waitFor({ state: 'visible' });
  const users = await page.evaluate(async () => (await import('./src/main.js')).localQuery('SELECT * FROM users'));
  assert.equal(users.length, 1);
  console.log('PASS invalid password, reload and persisted account without duplicates');
  await page.goto(new URL('index.html', base).href);
  await page.getByText('Abrir Aplicación', { exact: true }).click();
  assert.equal(new URL(page.url()).pathname.endsWith('/app.html'), true);
  console.log('PASS landing route');
  const delayed = await browser.newContext({ serviceWorkers: 'block' });
  let releaseModule;
  const moduleGate = new Promise(resolve => { releaseModule = resolve; });
  await delayed.route('**/src/main.js', async route => { await moduleGate; await route.continue(); });
  const dp = await delayed.newPage();
  await dp.goto(new URL('app.html', base).href, { waitUntil: 'commit' });
  await dp.locator('#login-button').waitFor({ state: 'attached' });
  assert.equal(await dp.locator('#login-button').isDisabled(), true);
  assert.equal(await dp.getByText('Abrir Aplicación', { exact: true }).isDisabled(), true);
  releaseModule();
  await dp.getByText('Abrir Aplicación', { exact: true }).click();
  await dp.getByRole('button', { name: 'Entrar', exact: true }).click();
  await dp.locator('#dashboard').waitFor({ state: 'visible' });
  await delayed.close();
  console.log('PASS login waits for delayed initialization');
  const broken = await browser.newContext({ serviceWorkers: 'block' });
  await broken.addInitScript(() => { indexedDB.open = () => { throw new Error('storage denied test'); }; });
  const badPage = await broken.newPage();
  await badPage.goto(new URL('app.html', base).href);
  await badPage.getByText('Abrir Aplicación', { exact: true }).click();
  await badPage.getByRole('alert').filter({ hasText: 'storage denied test' }).waitFor();
  assert.equal(await badPage.getByRole('button', { name: 'Entrar', exact: true }).isDisabled(), true);
  console.log('PASS initialization failure is visible and login disabled');
  await broken.close();
  for (const keyPath of ['id', null]) {
    const migrated = await browser.newContext({ serviceWorkers: 'block' });
    const mp = await migrated.newPage();
    await mp.goto(new URL('manifest.json', base).href);
    await mp.evaluate(keyPath => new Promise((resolve, reject) => {
      const r = indexedDB.open('ERP_Lipigas_Ancahual', 1);
      r.onupgradeneeded = () => {
        const db = r.result;
        const users = db.createObjectStore('users', keyPath ? { keyPath } : {});
        const admin = { id: 'existing-admin', username: 'admin', password_hash: 'existing-password', full_name: 'Existing Admin', role: 'admin' };
        keyPath ? users.add(admin) : users.add(admin, admin.id);
        const products = db.createObjectStore('products', { keyPath: 'id' });
        products.add({ id: 'keep-me', name: 'Existing product', price: 123 });
      };
      r.onerror = () => reject(r.error);
      r.onsuccess = () => { r.result.close(); resolve(); };
    }), keyPath);
    await mp.goto(new URL('app.html', base).href);
    await mp.getByText('Abrir Aplicación', { exact: true }).click();
    await mp.locator('#password').fill('existing-password');
    await mp.getByRole('button', { name: 'Entrar', exact: true }).click();
    await mp.locator('#dashboard').waitFor({ state: 'visible' });
    assert.equal(await mp.locator('#userName').textContent(), 'Existing Admin');
    const records = await mp.evaluate(async () => {
      const { localQuery } = await import('./src/main.js');
      return { users: await localQuery('SELECT * FROM users'), products: await localQuery('SELECT * FROM products') };
    });
    assert.equal(records.users.length, 1);
    assert.equal(records.users[0].password_hash, 'existing-password');
    assert.deepEqual(records.products, [{ id: 'keep-me', name: 'Existing product', price: 123 }]);
    await mp.reload();
    await mp.getByText('Abrir Aplicación', { exact: true }).click();
    await mp.locator('#password').fill('existing-password');
    await mp.getByRole('button', { name: 'Entrar', exact: true }).click();
    await mp.locator('#dashboard').waitFor({ state: 'visible' });
    await migrated.close();
    console.log('PASS v1 migration preserves account/password/product and reload, keyPath=' + keyPath);
  }
  await page.evaluate(() => navigator.serviceWorker.ready);
  await page.reload();
  await context.setOffline(true);
  await page.goto(new URL('app.html', base).href);
  await page.getByText('Abrir Aplicación', { exact: true }).click();
  await page.getByRole('button', { name: 'Entrar', exact: true }).click();
  await page.locator('#dashboard').waitFor({ state: 'visible' });
  await context.setOffline(false);
  console.log('PASS cached offline login');
  assert.deepEqual(errors, []);
} finally {
  console.log('pageErrors:', JSON.stringify(errors));
  await browser.close();
}
